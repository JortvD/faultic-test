async function inboxCodeAfterDelivery(page, email) {
  await page.getByLabel('Verification code').waitFor();
  const inbox = process.env.FIELDLINE_TEST_MAIL_URL ?? 'http://127.0.0.1:18096';
  const search = await fetch(inbox + '/api/v1/search?' + new URLSearchParams({ query: 'to:' + email }));
  assert(search.ok);
  const { messages } = await search.json();
  const delivery = await fetch(inbox + '/api/v1/message/' + messages[0].ID);
  assert(delivery.ok);
  return (await delivery.json()).Text.match(/signup page: ([A-F0-9]{16})/)[1];
}

